// A dependency-free SHA-256, so the ethics layer can hash a request on the
// desktop (Node), in the Electron shell, and inside the iOS WebView with the
// exact same code and no import of node:crypto. The layer stores a hash of the
// offending content, never the content itself, so this function is part of the
// privacy posture, not a convenience.
//
// Standard FIPS 180-4 SHA-256 over UTF-8 bytes. Verified in test/ethics.test.ts
// against published vectors.

