// The Vault settings sheet's words (Vault M7 wave 2; CX Y1 to Y10): stream
// F's M7 lines in lib/vaultCopy.ts, mapped onto the sheet's copy shape
// (stream G's `VaultSettingsSheetCopy`), so the sheet stays presentational
// and every string still lives in vaultCopy.ts under its guards. One mapper,
// built once; a test holds that every key is filled.
import { PACK_BY_CLASS } from 'os-code/protocol';
import type { VaultSettingsSheetCopy } from '../components/vault/VaultSettingsSheet.js';
import {
  VAULT_ADD_FOLDER,
  VAULT_ADD_TAG,
  VAULT_AGENT_FOLDER_ANYWHERE,
  VAULT_AGENT_FOLDER_SUB,
  VAULT_EXCLUDE_SUB,
  VAULT_HANDOFF_SUB,
  VAULT_LOCAL_ONLY_SUB,
  VAULT_PACK_SIZE_CLOUD,
  VAULT_PACK_SIZE_MACHINE_ABOVE,
  VAULT_PACK_SIZE_NEEDS_CONTEXT,
  VAULT_PACK_SIZE_SUB,
  VAULT_SETTINGS_BUILT_IN,
  VAULT_SETTINGS_CHOICES,
  VAULT_SETTINGS_DELETE_FOR_GOOD,
  VAULT_SETTINGS_DEVICE_FOOTER,
  VAULT_SETTINGS_FAILED,
  VAULT_SETTINGS_FIRST_CHANGE,
  VAULT_SETTINGS_FROM_MACHINE,
  VAULT_SETTINGS_FROM_OBSIDIAN,
  VAULT_SETTINGS_FROM_OBSIDIAN_MORE,
  VAULT_SETTINGS_MERGED,
  VAULT_SETTINGS_NONE,
  VAULT_SETTINGS_OBSIDIAN_EXCLUDED,
  VAULT_SETTINGS_OBSIDIAN_EXCLUDED_SUB,
  VAULT_SETTINGS_OBSIDIAN_OWN,
  VAULT_SETTINGS_ROWS,
  VAULT_SETTINGS_SAVED,
  VAULT_SETTINGS_SAVING,
  VAULT_SETTINGS_SECTIONS,
  VAULT_SETTINGS_TAG_PLACEHOLDER,
  VAULT_SETTINGS_TITLE,
  VAULT_SETTINGS_UNREADABLE,
  VAULT_SWITCH_MEMORY_OFF,
  VAULT_SWITCH_PROJECT_OFF,
  vaultAttachmentsValue,
  vaultNotesInChatsSub,
  vaultRemoveEntry,
  vaultSettingsSameField,
  vaultSettingsSetAside,
  vaultSettingsTodayIs,
  vaultSettingsUseYours,
} from './vaultCopy.js';

const R = VAULT_SETTINGS_ROWS;
const C = VAULT_SETTINGS_CHOICES;

/** The sheet's copy, from vaultCopy.ts. `byClass` is the pack table the
 *  Notes in chats sub is built from (default the core's `PACK_BY_CLASS`), so
 *  the sub never outruns the eval. */
export function vaultSettingsSheetCopy(
  byClass: Readonly<Record<string, string>> = PACK_BY_CLASS,
): VaultSettingsSheetCopy {
  return {
    title: VAULT_SETTINGS_TITLE,
    sections: { ...VAULT_SETTINGS_SECTIONS },
    saving: VAULT_SETTINGS_SAVING,
    saved: VAULT_SETTINGS_SAVED,
    savedMerged: VAULT_SETTINGS_MERGED,
    saveFailed: VAULT_SETTINGS_FAILED,
    firstChange: VAULT_SETTINGS_FIRST_CHANGE,
    unreadable: VAULT_SETTINGS_UNREADABLE,
    conflict: vaultSettingsSameField,
    useYours: vaultSettingsUseYours,
    fromObsidian: VAULT_SETTINGS_FROM_OBSIDIAN,
    fromObsidianLine: VAULT_SETTINGS_FROM_OBSIDIAN_MORE,
    obsidianKeepsOwn: VAULT_SETTINGS_OBSIDIAN_OWN,
    obsidianExcluded: VAULT_SETTINGS_OBSIDIAN_EXCLUDED,
    obsidianExcludedSub: VAULT_SETTINGS_OBSIDIAN_EXCLUDED_SUB,
    fromMachine: VAULT_SETTINGS_FROM_MACHINE,
    builtIn: VAULT_SETTINGS_BUILT_IN,
    setAside: vaultSettingsSetAside,
    topOfVault: C.newNotes.root,
    newNotesCurrent: C.newNotes.current,
    none: VAULT_SETTINGS_NONE,
    attachmentsValue: vaultAttachmentsValue,
    newNotesIn: R.newNotes,
    openIn: R.openMode,
    openRead: C.openMode.read,
    openEdit: C.openMode.edit,
    sortBy: R.sort,
    sortName: C.sort.name,
    sortModified: C.sort.modified,
    sortCreated: C.sort.created,
    deleteLabel: R.delete,
    deleteTrash: C.delete.trash,
    deleteForGood: C.delete.permanent,
    deleteForGoodSub: VAULT_SETTINGS_DELETE_FOR_GOOD,
    excluded: R.exclude,
    excludedSub: VAULT_EXCLUDE_SUB,
    localOnly: R.localOnly,
    localOnlySub: VAULT_LOCAL_ONLY_SUB,
    addFolder: VAULT_ADD_FOLDER,
    addTag: VAULT_ADD_TAG,
    tagPlaceholder: VAULT_SETTINGS_TAG_PLACEHOLDER,
    remove: vaultRemoveEntry,
    agentWrites: R.agentFolder,
    agentWritesSub: VAULT_AGENT_FOLDER_SUB,
    agentAnywhere: VAULT_AGENT_FOLDER_ANYWHERE,
    notesInChats: R.context,
    notesInChatsSub: vaultNotesInChatsSub(byClass),
    handoff: R.handoff,
    handoffSub: VAULT_HANDOFF_SUB,
    projectOff: VAULT_SWITCH_PROJECT_OFF,
    memoryOff: VAULT_SWITCH_MEMORY_OFF,
    room: R.packSize,
    roomSub: VAULT_PACK_SIZE_SUB,
    roomSmall: C.packSize.small,
    roomNormal: C.packSize.normal,
    roomLarge: C.packSize.large,
    roomSpend: VAULT_PACK_SIZE_CLOUD,
    roomNeedsContext: VAULT_PACK_SIZE_NEEDS_CONTEXT,
    roomAboveLarge: VAULT_PACK_SIZE_MACHINE_ABOVE,
    deviceFooter: VAULT_SETTINGS_DEVICE_FOOTER,
    dailyFolder: R.dailyFolder,
    dateFormat: R.dateFormat,
    today: vaultSettingsTodayIs,
    template: R.template,
    templatesFolder: R.templatesFolder,
    newLinks: R.linkStyle,
    wikilinks: C.linkStyle.wiki,
    markdownLinks: C.linkStyle.markdown,
    linkPaths: R.linkFormat,
    linkShortest: C.linkFormat.shortest,
    linkRelative: C.linkFormat.relative,
    linkAbsolute: C.linkFormat.absolute,
    attachmentsFolder: R.attachments,
    font: R.font,
    fontDefault: C.font.default,
    fontSerif: C.font.serif,
    fontMono: C.font.mono,
    size: R.size,
    sizeSmaller: C.size.smaller,
    sizeDefault: C.size.default,
    sizeLarger: C.size.larger,
    whereLives: R.where,
  };
}
